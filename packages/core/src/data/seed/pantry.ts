type Base = CatalogEntry["base"];
type More = Omit<CatalogEntry, "key" | "name" | "en" | "side" | "aisle" | "base">;

const m = (key: string, name: string, en: string, side: CatalogEntry["side"], aisle: CatalogEntry["aisle"], base: Base, extra: More = {}): CatalogEntry => ({
  key,
  name,
  en,
  side,
  aisle,
  base,
  ...extra,
});
const meat = (key: string, name: string, en: string, base: Base = "g", extra: More = {}) => m(key, name, en, "market", "Kasap", base, { pack: { size: 500, unit: "g" }, ...extra });
const dairy = (key: string, name: string, en: string, base: Base, extra: More = {}) => m(key, name, en, "market", "Süt ve kahvaltılık", base, extra);
const dry = (key: string, name: string, en: string, extra: More = {}) => m(key, name, en, "market", "Bakliyat ve kuru gıda", "g", { perCup: 170, perTbsp: 10, ...extra });
const jar = (key: string, name: string, en: string, base: Base, extra: More = {}) => m(key, name, en, "market", "Bakliyat ve kuru gıda", base, extra);
const spice = (key: string, name: string, en: string) => m(key, name, en, "market", "Baharat", "g", { perTbsp: 6, staple: true });
const bakery = (key: string, name: string, en: string, base: Base = "adet", extra: More = {}) => m(key, name, en, "market", "Fırın ve hamur", base, extra);
const frozen = (key: string, name: string, en: string, extra: More = {}) => m(key, name, en, "market", "Dondurulmuş", "g", extra);
const other = (key: string, name: string, en: string, base: Base, extra: More = {}) => m(key, name, en, "market", "Diğer", base, extra);
const veg = (key: string, name: string, en: string, base: Base = "g", extra: More = {}) => m(key, name, en, "pazar", "Sebze", base, extra);
const herb = (key: string, name: string, en: string) => m(key, name, en, "pazar", "Yeşillik", "demet");
const fruit = (key: string, name: string, en: string, base: Base = "g", extra: More = {}) => m(key, name, en, "pazar", "Meyve", base, extra);
/** Alcoholic drinks: a recipe using one must carry an alcohol-free substitute and the containsAlcohol tag. */
